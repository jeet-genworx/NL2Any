"""State carrier, update values, and context container for FSM pipeline runs."""

import time
from collections import defaultdict
from dataclasses import dataclass, field
from typing import Any

from backend.src.core.query_processing.pipeline.fsm.events import (
    ExecutionCompleted,
    GuardrailCompleted,
    PolicyCompleted,
    QueryGenerationCompleted,
    SpellingCompleted,
    StageEvent,
    TableSelectionCompleted,
    ValidationCompleted,
)
from backend.src.core.query_processing.pipeline.fsm.states import PipelineState
from backend.src.core.query_processing.pipeline.selector import package_selected_schema
from backend.src.data.models.schema import DatabaseSchema, DatabaseType
from backend.src.data.models.targets import DatabaseTarget
from backend.src.schemas.pipeline import (
    ExecutionResult,
    GeneratedQuery,
    GuardrailResult,
    PolicyResult,
    RelevantSchema,
    SpellingCorrectionResult,
    ValidationResult,
)


class _ClearSentinel:
    """Sentinel indicating that a field should be cleared to None."""

    def __repr__(self) -> str:
        return "<CLEAR>"


CLEAR = _ClearSentinel()


@dataclass(frozen=True)
class ContextUpdates:
    """Pure description of context mutations generated by the transition function."""

    selector_retries: int | None = None
    validation_retries: int | None = None
    attempts: int | None = None
    s1_system_retry: str | _ClearSentinel | None = None
    s2_system_retry: str | _ClearSentinel | None = None
    s3_system_retry: str | _ClearSentinel | None = None
    error: str | _ClearSentinel | None = None
    basic_answer: str | _ClearSentinel | None = None
    initial_val_checked: bool | None = None
    stage_3_fallthrough_allowed: bool | None = None


@dataclass(frozen=True)
class TransitionDecision:
    """The pure outcome of evaluating a state transition."""

    next_state: PipelineState
    updates: ContextUpdates = ContextUpdates()


@dataclass
class PipelineContext:
    """Carries complete data and telemetry across FSM state transitions."""

    run_id: str
    database_target: DatabaseTarget | None = None
    db_type: DatabaseType = DatabaseType.POSTGRESQL
    target_name: str = "postgres"
    schema: DatabaseSchema | None = None

    question: str = ""
    processed_question: str = ""
    jargons: list[str] = field(default_factory=list)

    # Rerun and branching flags
    is_rerun: bool = False
    entry_stage: str = "fresh"  # "fresh", "table_selection", "query_generation", "validation"
    stage_1_frozen: bool = False
    initial_val_checked: bool = False
    stage_3_fallthrough_allowed: bool = False

    # Timestamps
    created_at: float = field(default_factory=time.time)
    updated_at: float = field(default_factory=time.time)

    # Feedback and prompt composition state
    feedback_history: list[dict[str, Any]] = field(default_factory=list)
    applicable_feedback: dict[str, str] = field(default_factory=dict)
    s1_user_guidance: str | None = None
    s2_user_guidance: str | None = None
    s3_user_guidance: str | None = None
    s1_system_retry: str | None = None
    s2_system_retry: str | None = None
    s3_system_retry: str | None = None

    # Retry and loop counters
    selector_retries: int = 0
    validation_retries: int = 0
    attempts: int = 1
    max_retries: int = 3

    # Stage artifacts
    spelling_result: SpellingCorrectionResult | None = None
    guardrail_result: GuardrailResult | None = None
    selected_objects: list[str] = field(default_factory=list)
    relevant_schema: RelevantSchema | None = None
    generated_query: GeneratedQuery | None = None
    validation_result: ValidationResult | None = None
    policy_result: PolicyResult | None = None
    execution_result: ExecutionResult | None = None

    # Telemetry and telemetry accumulators
    stage_providers: dict[str, str] = field(default_factory=dict)
    stage_tokens: dict[str, int] = field(default_factory=dict)
    accum_stage_latency_ms: dict[str, float] = field(default_factory=lambda: defaultdict(float))

    # Error and exit payload
    error: str | None = None
    basic_answer: str | None = None

    def apply_updates(self, updates: ContextUpdates) -> None:
        """Apply pure ContextUpdates to this context instance."""
        if updates.selector_retries is not None:
            self.selector_retries = updates.selector_retries
        if updates.validation_retries is not None:
            self.validation_retries = updates.validation_retries
        if updates.attempts is not None:
            self.attempts = updates.attempts
        if updates.initial_val_checked is not None:
            self.initial_val_checked = updates.initial_val_checked
        if updates.stage_3_fallthrough_allowed is not None:
            self.stage_3_fallthrough_allowed = updates.stage_3_fallthrough_allowed

        if updates.s1_system_retry is CLEAR:
            self.s1_system_retry = None
        elif updates.s1_system_retry is not None:
            self.s1_system_retry = updates.s1_system_retry

        if updates.s2_system_retry is CLEAR:
            self.s2_system_retry = None
        elif updates.s2_system_retry is not None:
            self.s2_system_retry = updates.s2_system_retry

        if updates.s3_system_retry is CLEAR:
            self.s3_system_retry = None
        elif updates.s3_system_retry is not None:
            self.s3_system_retry = updates.s3_system_retry

        if updates.error is CLEAR:
            self.error = None
        elif updates.error is not None:
            self.error = updates.error

        if updates.basic_answer is CLEAR:
            self.basic_answer = None
        elif updates.basic_answer is not None:
            self.basic_answer = updates.basic_answer

    def record_event_artifacts(self, event: StageEvent) -> None:
        """Record stage outputs from completed stage events into context."""
        if isinstance(event, SpellingCompleted):
            self.spelling_result = event.result
            self.processed_question = event.result.corrected_question
        elif isinstance(event, GuardrailCompleted):
            self.guardrail_result = event.result
        elif isinstance(event, TableSelectionCompleted):
            self.selected_objects = list(event.result.selected_objects)
            if self.schema and self.selected_objects:
                self.relevant_schema = package_selected_schema(self.schema, self.selected_objects)
        elif isinstance(event, QueryGenerationCompleted):
            self.generated_query = event.query
        elif isinstance(event, ValidationCompleted):
            self.validation_result = event.result
        elif isinstance(event, PolicyCompleted):
            self.policy_result = event.result
        elif isinstance(event, ExecutionCompleted):
            self.execution_result = event.result

    def record_tokens(self, state: PipelineState, tokens: int) -> None:
        """Record token consumption for the active stage."""
        if not tokens:
            return
        key = state.value
        self.stage_tokens[key] = self.stage_tokens.get(key, 0) + tokens
